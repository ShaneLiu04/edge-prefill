#!/usr/bin/env python3
"""AR005 T010: emit the FR-6 benchmark conf registry into benchmarks/matrix/.

FR-6 grid = budget {0.15, 0.25, 0.35} x attn_top_k {12, 24} x
pool_branches {off, on} x query_gating {v2(embedding), off} = 24 sparse
grid points, plus one dense reference conf. The registry is checked in so
the exact grid under test is auditable (FP9: registered confs must cover
the full grid).

Confs are machine-neutral: model / data_dir / embedding paths are injected
at run time by benchmarks/scripts/run_matrix_ar005.py. Every sparse grid
point runs with the embedding model active (semantic selection); the qg
dimension varies only the attention-side mechanism (query-gated 2D gather
vs scalar top-k).

Regenerating must be idempotent: run from anywhere, output bytes stable.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(ROOT, "benchmarks", "matrix")

BUDGETS = ["b015", "b025", "b035"]
ATTNS = ["a12", "a24"]
POOLS = ["pool0", "pool1"]
QGS = ["qgoff", "qgv2"]


def conf_body(budget, attn, pool, qg):
    pool_on = pool == "pool1"
    qg_on = qg == "qgv2"
    lines = [
        "# AR005 FR-6 grid point: budget=0.%s attn_top_k=%s pool=%s qg=%s" % (
            budget[2:], attn[1:], "on" if pool_on else "off", "v2" if qg_on else "off"),
        "# Generated by benchmarks/scripts/gen_matrix_conf.py - do not edit.",
        "# Machine paths (model / data_dir / embedding model) are injected by",
        "# run_matrix_ar005.py; the embedding model is active for every grid",
        "# point (semantic selection), qg only toggles the attention gather.",
        "mode = balanced",
        "budget = 0." + budget[2:],
        "attn_top_k = " + attn[1:],
        "pool_branches = " + ("true" if pool_on else "false"),
        "query_gating = " + ("true" if qg_on else "false"),
    ]
    if qg_on:
        # AR005 fix: each query group's own span is mandatory (local
        # context), so the scored extras need their own budget on top.
        # 512 rows/group is the validated minimum for 4K needle recall;
        # the grid keeps it fixed so the other axes stay comparable.
        lines += [
            "query_chunk_size = 128",
            "query_top_k = 512",
        ]
    lines += [
        "embedding_model =",
        "threads = 16",
        "warmup = 1",
        "max_new_tokens = 16",
        "repeats = 3",
        "",
    ]
    return "\n".join(lines)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    dense = [
        "# AR005 FR-6 dense reference (budget=1.0, mode=dense).",
        "# Generated by benchmarks/scripts/gen_matrix_conf.py - do not edit.",
        "# Measured once per dataset; every sparse grid point of the same",
        "# dataset pairs against this reference for net speedup.",
        "mode = dense",
        "budget = 1.0",
        "embedding_model =",
        "threads = 16",
        "warmup = 1",
        "max_new_tokens = 16",
        "repeats = 3",
        "",
    ]
    path = os.path.join(OUT_DIR, "dense.conf")
    with open(path, "w") as f:
        f.write("\n".join(dense))
    written.append("dense.conf")

    for b in BUDGETS:
        for a in ATTNS:
            for p in POOLS:
                for q in QGS:
                    name = "%s-%s-%s-%s.conf" % (b, a, p, q)
                    with open(os.path.join(OUT_DIR, name), "w") as f:
                        f.write(conf_body(b, a, p, q))
                    written.append(name)

    print("wrote %d confs to %s" % (len(written), OUT_DIR))
    assert len(written) == 25, "FR-6 registry must be 24 grid points + dense"


if __name__ == "__main__":
    main()
